function pickPoolForSection(sectionAr: string, category: string): string[] {
  if (/طواجن|فرن/i.test(sectionAr)) return SECTION_FALLBACK_POOLS.tagines;
  if (/شوايات|لحوم/i.test(sectionAr)) return SECTION_FALLBACK_POOLS.grills_meats;
  if (/دجاج/i.test(sectionAr)) return SECTION_FALLBACK_POOLS.chicken;
  if (/باستا/i.test(sectionAr)) return SECTION_FALLBACK_POOLS.pasta;
  if (/سي فود/i.test(sectionAr)) return SECTION_FALLBACK_POOLS.seafood;
  if (/شورب/i.test(sectionAr)) return SECTION_FALLBACK_POOLS.soups;
  if (/سلاطات|مقبلات|جانبية/i.test(sectionAr)) return SECTION_FALLBACK_POOLS.salads_mezze;
  if (/كرواسون|أومليت|فطار|بيض/i.test(sectionAr)) return SECTION_FALLBACK_POOLS.breakfast_pastry;
  if (/الحلو|حلويات/i.test(sectionAr)) return SECTION_FALLBACK_POOLS.sweet_pies;
  if (/ساندويتش/i.test(sectionAr)) return SECTION_FALLBACK_POOLS.sandwiches;
  if (category === 'appetizers') return SECTION_FALLBACK_POOLS.salads_mezze;
  return SECTION_FALLBACK_POOLS.grills_meats;
}

function ensureDistinctSectionImages(items: MenuItem[]): MenuItem[] {
  const usedBySection = new Map<string, Set<string>>();
  const countBySection = new Map<string, number>();

  return items.map((item) => {
    const sectionKey = item.prepNoteAr || item.category;
    const used = usedBySection.get(sectionKey) ?? new Set<string>();
    const idx = countBySection.get(sectionKey) ?? 0;
    countBySection.set(sectionKey, idx + 1);

    let nextUrl = item.imageUrl;
    if (used.has(nextUrl)) {
      const pool = pickPoolForSection(sectionKey, item.category);
      const rawChoice = pool[idx % pool.length];
      nextUrl = rawChoice.startsWith('/') ? `${rawChoice}?v=${idx + 1}` : u(rawChoice, idx + 1);
      if (used.has(nextUrl)) {
        nextUrl = `${nextUrl}${nextUrl.includes('?') ? '&' : '?'}item=${idx + 1}`;
      }
    }
    used.add(nextUrl);
    usedBySection.set(sectionKey, used);

    return {
      ...item,
      imageUrl: nextUrl,
    };
  });
}

function withPopularTag(items: MenuItem[]): MenuItem[] {
  const distinctItems = ensureDistinctSectionImages(items);
  return distinctItems.map((item) =>
    item.featured || item.popular
      ? {
          ...item,
          featured: true,
          popular: true,
          tags: item.tags?.includes('popular') ? item.tags : [...(item.tags ?? []), 'popular'],
        }
      : item
  );
}

