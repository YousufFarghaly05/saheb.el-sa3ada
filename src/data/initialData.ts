export function getEffectiveBranchConfig(
  branchId: BranchId,
  store?: Pick<StoreState, 'branchSettings'> | null
): BranchConfig {
  const base = BRANCH_CONFIGS[branchId];
  const s = store?.branchSettings;
  if (!s) return base;
  return {
    ...base,
    addressAr: s.addressAr?.trim() ? s.addressAr : base.addressAr,
    addressEn: s.addressEn?.trim() ? s.addressEn : base.addressEn,
    phone: s.phone?.trim() ? s.phone : base.phone,
    whatsappIntl: s.whatsappIntl?.trim() ? s.whatsappIntl : base.whatsappIntl,
    vodafoneCash: s.vodafoneCash?.trim() ? s.vodafoneCash : base.vodafoneCash,
    instapay: s.instapay?.trim() ? s.instapay : base.instapay,
  };
}

